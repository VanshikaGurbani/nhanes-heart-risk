"""Turn the results dict into docs/RESULTS.md and the README headline paragraph.

Nothing in the generated text is typed by hand: every figure is formatted from `results`.
Percent signs are used instead of decimals in prose. There are no em dashes.
"""

from __future__ import annotations

import re
from pathlib import Path

NAMES = {
    "age_sex_baseline": "Age and sex only (reference)",
    "logistic_regression": "Logistic regression",
    "random_forest": "Random forest",
    "xgboost": "XGBoost",
}
FEATURE_NAMES = {
    "age_years": "age",
    "bmi": "BMI",
    "waist_cm": "waist",
    "sbp_mean": "systolic BP",
    "dbp_mean": "diastolic BP",
    "total_chol": "total cholesterol",
    "hdl": "HDL cholesterol",
    "hba1c": "HbA1c",
    "fasting_glucose": "fasting glucose",
    "drinks_per_day": "drinks per day",
    "sex": "sex",
    "smoking_status": "smoking",
    "diabetes": "diabetes",
    "ever_heavy_drinker": "ever heavy drinker",
}


def pct(x: float, d: int = 1) -> str:
    return f"{x * 100:.{d}f}%"


def ci_pct(point: float, lo: float, hi: float, d: int = 1) -> str:
    return f"{pct(point, d)} ({pct(lo, d)} to {pct(hi, d)})"


def pp(x: float, d: int = 1) -> str:
    return f"{x * 100:+.{d}f} pp"


def pp_ci(t: list[float]) -> str:
    return f"{pp(t[0])} (95% CI {pp(t[1])} to {pp(t[2])})"


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _model_rows(R: dict) -> list[list[str]]:
    rows = []
    for m, v in R["models"].items():
        t = v["test"]
        rows.append(
            [
                NAMES[m],
                pct(v["valid"]["pr_auc"]),
                ci_pct(t["roc_auc"], *t["roc_auc_ci"]),
                ci_pct(t["pr_auc"], *t["pr_auc_ci"]),
                f"{t['brier'] * 100:.2f}%",
            ]
        )
    return rows


def headline(R: dict) -> str:
    sel = R["selection"]["selected"]
    test = R["data"]["splits"]["test"]
    lr = R["models"]["logistic_regression"]["test"]
    xg = R["models"]["xgboost"]["test"]
    base = R["models"]["age_sex_baseline"]["test"]
    d = R["paired_differences_test"]["xgboost_minus_logistic_regression"]
    rt = R["models"][sel]["recall_target"]
    tt = rt["test"]
    xgb_vs_lr = (
        "XGBoost did not beat logistic regression"
        if d["roc_auc"][1] <= 0 <= d["roc_auc"][2]
        else (
            "XGBoost beat logistic regression"
            if d["roc_auc"][0] > 0
            else "XGBoost was worse than logistic regression"
        )
    )
    return (
        f"On {R['data']['n_total']:,} U.S. adults from four NHANES survey cycles "
        f"({R['data']['positives_total']:,} reporting coronary heart disease, angina or a heart attack), "
        f"models trained on the {R['data']['splits']['train']['survey_years']} cycles and tested on the later "
        f"{test['survey_years']} cycle ({test['n']:,} adults, "
        f"{test['positives']} cases) reached a ROC-AUC of **{ci_pct(lr['roc_auc'], *lr['roc_auc_ci'])}** for "
        f"logistic regression and **{ci_pct(xg['roc_auc'], *xg['roc_auc_ci'])}** for XGBoost. "
        f"{xgb_vs_lr} (ROC-AUC gap {pp_ci(d['roc_auc'])}). "
        f"Age and sex alone already reach {pct(base['roc_auc'])}. "
        f"With the threshold set on validation data to catch 90% of cases, the selected model "
        f"({NAMES[sel].lower()}) caught **{pct(tt['recall'])}** of cases on the test cycle, flagged "
        f"**{pct(tt['flagged_share'])}** of all adults, and raised **{tt['false_alarms_per_case_found']:.1f}** "
        f"false alarms per case found. Labels are self-reported, this is not a clinical diagnosis, and the "
        f"results do not transfer to hospital patients."
    )


def render_results(R: dict) -> str:
    sel = R["selection"]["selected"]
    D = R["data"]
    out: list[str] = []
    w = out.append
    w("# Results\n")
    w(
        "Generated by `nhanes run-all` from `docs/results/results.json`. Do not edit by hand: every number "
        "below is produced by code. Percent figures are shares of people unless a column says otherwise; "
        "`pp` means percentage points. Intervals are bootstrap 95% intervals "
        f"({R['meta']['n_boot']} resamples of the test rows, seed {R['meta']['seed']}).\n"
    )
    w(
        '**Read this first.** Labels are self-reported answers to "has a doctor ever told you that you '
        'had ...". This is not a clinical diagnosis. NHANES is a survey of the U.S. household population, '
        "so results do not transfer to hospital patients. See the Limitations section of the README.\n"
    )

    w("## 1. Headline\n")
    w(headline(R) + "\n")

    w("## 2. Data\n")
    w("### 2.1 Splits (temporal: earlier cycles train, a later one validates, the latest tests)\n")
    w(
        table(
            ["Split", "Cycles", "Years", "Adults", "Cases", "Prevalence"],
            [
                [
                    s,
                    ", ".join(v["cycles"]),
                    v["survey_years"],
                    f"{v['n']:,}",
                    f"{v['positives']:,}",
                    pct(v["prevalence"]),
                ]
                for s, v in D["splits"].items()
            ],
        )
        + "\n"
    )
    if "funnel" in D:
        w("### 2.2 Cohort funnel\n")
        w(
            table(
                [
                    "Cycle",
                    "All participants",
                    "Adults 20+",
                    "Adults with the heart questions",
                    "Adults with a known label",
                ],
                [
                    [
                        f["cycle"],
                        f"{f['all_participants']:,}",
                        f"{f['adults_20_plus']:,}",
                        f"{f['adults_with_mcq']:,}",
                        f"{f['adults_with_label']:,}",
                    ]
                    for f in D["funnel"]
                ],
            )
            + "\n"
        )
        w(
            "People with no yes answer and at least one refused, don't know or missing answer among the three "
            "heart questions have an unknown label and are dropped (counted in the last two columns).\n"
        )
    lc = D["label_components"]
    w("### 2.3 What the label is made of\n")
    w(
        f"Label = yes to coronary heart disease, angina or heart attack. Counts among labelled adults "
        f"(people can have more than one): coronary heart disease {lc['chd']:,}, angina {lc['angina']:,}, "
        f"heart attack {lc['heart_attack']:,}. Not part of the label and never used as features: "
        f"congestive heart failure ({lc['chf']:,} people) and stroke ({lc['stroke']:,}).\n"
    )
    pv = list(D["prevalence_by_cycle"].values())
    trend = "rises" if pv[-1] > pv[0] else "falls" if pv[-1] < pv[0] else "stays flat"
    w(
        "Prevalence by cycle: "
        + ", ".join(f"{c} {pct(v)}" for c, v in D["prevalence_by_cycle"].items())
        + f". The rate {trend} from the first cycle to the last, so the test cycle can have a different "
        "base rate from the training cycles.\n"
    )
    ms = D["missingness"]
    w("### 2.4 Missing values (share of adults)\n")
    w(
        table(
            ["Feature", "Train", "Valid", "Test"],
            [
                [
                    FEATURE_NAMES.get(c, c),
                    pct(ms["by_split"]["train"][c]),
                    pct(ms["by_split"]["valid"][c]),
                    pct(ms["by_split"]["test"][c]),
                ]
                for c in ms["overall"]
            ],
        )
        + "\n"
    )
    w(
        f"{pct(ms['examined_share'])} of adults were examined at the mobile exam centre; "
        f"{pct(ms['complete_case_share'])} have every feature present. Fasting glucose exists only for the "
        f"morning fasting subsample.\n"
    )
    if "validation" in R:
        w("### 2.5 Data quality checks\n")
        n_ok = sum(1 for c in R["validation"] if c["passed"])
        w(
            f"{n_ok} of {len(R['validation'])} automated checks passed (any failure stops the run). "
            "Details are printed by `nhanes validate`.\n"
        )

    w("## 3. Model comparison on the test cycle\n")
    w(
        "Hyperparameters were tuned on the validation cycle only. Valid PR-AUC is the validation score used for tuning.\n"
    )
    w(
        table(
            [
                "Model",
                "Valid PR-AUC",
                "Test ROC-AUC (95% CI)",
                "Test PR-AUC (95% CI)",
                "Test Brier score",
            ],
            _model_rows(R),
        )
        + "\n"
    )
    w(
        f"Prevalence on the test cycle is {pct(D['splits']['test']['prevalence'])}, so a model that guesses "
        f'"no heart disease" for everyone scores {pct(D["majority_class_accuracy_test"])} accuracy and '
        f"catches no one. PR-AUC of a model with no skill equals the prevalence.\n"
    )
    w("### 3.1 Paired differences on the same test rows\n")
    rows = []
    for k, v in R["paired_differences_test"].items():
        a, b = k.split("_minus_")
        rows.append([f"{NAMES[a]} minus {NAMES[b]}", pp_ci(v["roc_auc"]), pp_ci(v["pr_auc"])])
    w(table(["Comparison", "ROC-AUC gap", "PR-AUC gap"], rows) + "\n")
    d = R["paired_differences_test"]
    for m in ("xgboost", "random_forest"):
        v = d[f"{m}_minus_logistic_regression"]["roc_auc"]
        verdict = (
            "is not distinguishable from"
            if v[1] <= 0 <= v[2]
            else "is better than"
            if v[0] > 0
            else "is worse than"
        )
        w(f"* {NAMES[m]} {verdict} logistic regression on ROC-AUC (gap {pp_ci(v)}).")
    w("")

    w("## 4. Threshold choice and the cost of false alarms\n")
    w(
        "Missing a sick person is worse than a false alarm, so the threshold is the highest one that catches at "
        f"least {pct(R['models'][sel]['recall_target']['target'], 0)} of the cases **on the validation cycle**. "
        "It is then applied unchanged to the test cycle. The test cycle never chooses a threshold.\n"
    )
    rows = []
    for m, v in R["models"].items():
        rt = v["recall_target"]
        t = rt["test"]
        rows.append(
            [
                NAMES[m],
                pct(rt["threshold"]),
                pct(rt["valid"]["recall"]),
                ci_pct(t["recall"], *rt["test_recall_ci"]),
                ci_pct(t["precision"], *rt["test_precision_ci"]),
                pct(t["f1"]),
                pct(t["accuracy"]),
                pct(t["flagged_share"]),
                f"{t['false_alarms_per_case_found']:.1f}",
            ]
        )
    w(
        table(
            [
                "Model",
                "Threshold",
                "Valid recall",
                "Test recall (95% CI)",
                "Test precision (95% CI)",
                "Test F1",
                "Test accuracy",
                "Share flagged",
                "False alarms per case found",
            ],
            rows,
        )
        + "\n"
    )
    w("Confusion matrices on the test cycle at that threshold (rows are the truth):\n")
    rows = []
    for m, v in R["models"].items():
        t = v["recall_target"]["test"]
        rows.append([NAMES[m], f"{t['tn']:,}", f"{t['fp']:,}", f"{t['fn']:,}", f"{t['tp']:,}"])
    w(
        table(["Model", "True negatives", "False alarms", "Missed cases", "Cases caught"], rows)
        + "\n"
    )
    w("### 4.1 For reference: the default 0.5 threshold\n")
    rows = []
    for m, v in R["models"].items():
        t = v["default_threshold_test"]
        rows.append(
            [
                NAMES[m],
                pct(t["accuracy"]),
                pct(t["precision"]),
                pct(t["recall"]),
                pct(t["f1"]),
                f"{t['tp']:,} of {t['tp'] + t['fn']:,}",
            ]
        )
    w(table(["Model", "Accuracy", "Precision", "Recall", "F1", "Cases caught"], rows) + "\n")
    w(
        "At 0.5 accuracy looks high only because most people are healthy; recall shows how few sick people "
        "are caught. That is why the recall-target threshold is the one used.\n"
    )
    w(f"### 4.2 Different recall targets ({NAMES[sel]})\n")
    rows = []
    for tr in R["threshold_tradeoff_selected"]:
        t = tr["test"]
        rows.append(
            [
                pct(tr["target_recall"], 0),
                pct(tr["threshold"]),
                pct(tr["valid"]["recall"]),
                pct(t["recall"]),
                pct(t["precision"]),
                pct(t["flagged_share"]),
                f"{t['false_alarms_per_case_found']:.1f}",
            ]
        )
    w(
        table(
            [
                "Target recall (valid)",
                "Threshold",
                "Valid recall",
                "Test recall",
                "Test precision",
                "Share flagged",
                "False alarms per case found",
            ],
            rows,
        )
        + "\n"
    )

    w("## 5. Model choice\n")
    ev = R["selection"]["evidence"]
    w(f"Rule (validation only): {R['selection']['rule']}.\n")
    w(
        table(
            ["Candidate", "Validation PR-AUC gap vs logistic regression (95% CI)", "Qualifies"],
            [
                [
                    NAMES[m],
                    pp_ci([e["pr_auc_gap_vs_logistic"], e["lo"], e["hi"]]),
                    "yes" if e["qualifies"] else "no",
                ]
                for m, e in ev.items()
            ],
        )
        + "\n"
    )
    w(f"Selected model: **{NAMES[sel]}**. This is the model in the Streamlit app.\n")

    w("## 6. Calibration (test cycle)\n")
    rows = []
    for m, v in R["models"].items():
        c = v["calibration_test"]
        rows.append(
            [
                NAMES[m],
                f"{c['brier'] * 100:.2f}%",
                pct(c["ece"], 2),
                f"{c['intercept']:.2f}",
                f"{c['slope']:.2f}",
                pct(c["mean_predicted"], 2),
                pct(c["observed_rate"], 2),
            ]
        )
    w(
        table(
            [
                "Model",
                "Brier",
                "Expected calibration error",
                "Intercept",
                "Slope",
                "Mean predicted",
                "Observed rate",
            ],
            rows,
        )
        + "\n"
    )
    rc = R["recalibration_selected"]
    w(
        "Slope 1 and intercept 0 mean perfect calibration. "
        f"Platt scaling fitted on validation moved the selected model's Brier score from "
        f"{rc['raw']['brier'] * 100:.2f}% to {rc['platt_on_valid']['brier'] * 100:.2f}% and its expected "
        f"calibration error from {pct(rc['raw']['ece'], 2)} to {pct(rc['platt_on_valid']['ece'], 2)}.\n"
    )

    w("## 7. Missing-value strategies (test cycle, same tuned hyperparameters)\n")
    mv = R["missing_value_strategies"]
    w(
        table(
            ["Model", "Strategy", "ROC-AUC (95% CI)", "PR-AUC (95% CI)"],
            [
                [
                    NAMES[r["model"]],
                    r["strategy"],
                    ci_pct(r["roc_auc"], r["roc_auc_lo"], r["roc_auc_hi"]),
                    ci_pct(r["pr_auc"], r["pr_auc_lo"], r["pr_auc_hi"]),
                ]
                for r in mv["rows"]
            ],
        )
        + "\n"
    )
    w(
        "median_indicator: median fill plus a missing flag per feature. median: median fill only. iterative: each "
        "feature predicted from the others. native: XGBoost handles missing values itself.\n"
    )
    cc = mv["complete_case"]
    w(
        f"Complete-case analysis keeps only people with every feature present: {cc['n_train_complete']:,} of "
        f"{cc['n_train_total']:,} training rows and {cc['n_test_complete']:,} of {cc['n_test_total']:,} test rows "
        f"({cc['positives_test_complete']} test cases). On those test rows a logistic regression trained on "
        f"complete cases reaches ROC-AUC {pct(cc['complete_case_model_roc_auc'])} and PR-AUC "
        f"{pct(cc['complete_case_model_pr_auc'])}, against {pct(cc['median_indicator_model_roc_auc_same_rows'])} and "
        f"{pct(cc['median_indicator_model_pr_auc_same_rows'])} for the median_indicator model trained on all rows.\n"
    )

    w(f"## 8. Subgroups ({NAMES[sel]}, test cycle, 90% recall threshold)\n")
    for dim, title in (
        ("sex", "Sex"),
        ("age_band", "Age band"),
        ("race_ethnicity", "Race and ethnicity (description only, never a feature)"),
    ):
        w(f"### {title}\n")
        rows = []
        for r in R["subgroups_selected"][dim]:
            if "roc_auc" in r:
                rows.append(
                    [
                        r["group"],
                        f"{r['n']:,}",
                        r["positives"],
                        pct(r["prevalence"]),
                        ci_pct(r["roc_auc"], r["roc_auc_lo"], r["roc_auc_hi"]),
                        pct(r["recall"]),
                        pct(r["precision"]),
                        pct(r["flagged_share"]),
                    ]
                )
            else:
                rows.append(
                    [
                        r["group"],
                        f"{r['n']:,}",
                        r["positives"],
                        pct(r["prevalence"]),
                        "n/a",
                        "n/a",
                        "n/a",
                        "n/a",
                    ]
                )
        w(
            table(
                [
                    "Group",
                    "Adults",
                    "Cases",
                    "Prevalence",
                    "ROC-AUC (95% CI)",
                    "Recall",
                    "Precision",
                    "Share flagged",
                ],
                rows,
            )
            + "\n"
        )
    ab = [r for r in R["subgroups_selected"]["age_band"] if "recall" in r]
    if ab:
        lo = min(ab, key=lambda r: r["recall"])
        hi = max(ab, key=lambda r: r["recall"])
        w(
            f"At the overall 90% recall threshold the age bands are treated very differently: the {hi['group']} "
            f"band has recall {pct(hi['recall'])} with {pct(hi['flagged_share'])} of its adults flagged, while the "
            f"{lo['group']} band has recall {pct(lo['recall'])} ({lo['positives']} cases) with "
            f"{pct(lo['flagged_share'])} flagged. The overall recall target is reached largely by flagging "
            "most older adults.\n"
        )
    w(
        "Groups with few cases have wide intervals. Compare each group's precision with its prevalence: "
        "where prevalence is low, precision is low even for a good ranking.\n"
    )

    w("## 9. Survey weights (sensitivity check)\n")
    ws = R["weighted_sensitivity"]
    w(
        "The main models are unweighted: each respondent counts once. NHANES oversamples some groups and each "
        "person carries an exam weight that says how many people in the U.S. population they represent. "
        f"On the {ws['n_examined_test']:,} examined test participants:\n"
    )
    w(
        f"* Prevalence is {pct(ws['unweighted_prevalence'])} unweighted and {pct(ws['weighted_prevalence'])} weighted."
    )
    w(
        f"* The selected model's ROC-AUC is {pct(ws['selected_unweighted_roc_auc'])} unweighted and "
        f"{pct(ws['selected_weighted_roc_auc'])} weighted; PR-AUC is {pct(ws['selected_unweighted_pr_auc'])} and "
        f"{pct(ws['selected_weighted_pr_auc'])}."
    )
    w(
        f"* Training logistic regression with the weights instead of without changes weighted ROC-AUC from "
        f"{pct(ws['lr_unweighted_training_weighted_auc'])} to {pct(ws['lr_weighted_training_weighted_auc'])}, and "
        f"unweighted ROC-AUC from {pct(ws['lr_unweighted_training_unweighted_auc'])} to "
        f"{pct(ws['lr_weighted_training_unweighted_auc'])}."
    )
    w(
        "No design-based standard errors (strata and PSU) are computed, so the intervals in this file treat "
        "participants as independent draws.\n"
    )

    w("## 10. What drives the predictions\n")
    imp = R["importance"]
    w(
        f"### 10.1 Permutation importance, {NAMES[sel]} (test ROC-AUC drop when a feature is shuffled)\n"
    )
    w(
        table(
            ["Feature", "AUC drop", "Std over repeats"],
            [
                [
                    FEATURE_NAMES.get(r["feature"], r["feature"]),
                    pct(r["auc_drop_mean"], 2),
                    pct(r["auc_drop_std"], 2),
                ]
                for r in imp["permutation_selected"]
            ],
        )
        + "\n"
    )
    w("### 10.2 SHAP, XGBoost (mean absolute value, log-odds)\n")
    w(
        table(
            ["Feature", "Mean abs SHAP"],
            [
                [r["feature"].replace("_", " "), f"{r['mean_abs_shap']:.3f}"]
                for r in imp["shap_xgboost_mean_abs"][:12]
            ],
        )
        + "\n"
    )
    w("### 10.3 Logistic regression odds ratios (per 1 standard deviation, or category present)\n")
    w(
        table(
            ["Term", "Odds ratio"],
            [
                [r["feature"].replace("_", " "), f"{r['odds_ratio']:.2f}"]
                for r in R["odds_ratios_logistic"][:12]
            ],
        )
        + "\n"
    )
    w(
        "Importance describes what the model uses, not what causes disease. Cholesterol may look protective "
        "because people with heart disease are often treated with cholesterol-lowering drugs.\n"
    )

    w("## 11. Tuning grids and environment\n")
    for m in ("logistic_regression", "random_forest", "xgboost"):
        g = R["models"][m]["grid"]
        best = max(g, key=lambda r: r["valid_pr_auc"])
        w(
            f"* {NAMES[m]}: {len(g)} settings tried, best validation PR-AUC {pct(best['valid_pr_auc'])} at "
            + ", ".join(f"{k}={v}" for k, v in best.items() if k != "valid_pr_auc")
            + "."
        )
    mt = R["meta"]
    w(
        f"\nPython {mt['python']}, scikit-learn {mt['sklearn']}, XGBoost {mt['xgboost']}, pandas {mt['pandas']}, "
        f"seed {mt['seed']}.\n"
    )
    return "\n".join(out)


def readme_table(R: dict) -> str:
    """Small model comparison table for the README, formatted from results.json."""
    rows = []
    for m, v in R["models"].items():
        t, rt = v["test"], v["recall_target"]["test"]
        rows.append(
            [
                NAMES[m],
                ci_pct(t["roc_auc"], *t["roc_auc_ci"]),
                ci_pct(t["pr_auc"], *t["pr_auc_ci"]),
                pct(rt["recall"]),
                pct(rt["flagged_share"]),
                f"{rt['false_alarms_per_case_found']:.1f}",
            ]
        )
    return table(
        [
            "Model",
            "Test ROC-AUC (95% CI)",
            "Test PR-AUC (95% CI)",
            "Recall at the 90% threshold",
            "Share of adults flagged",
            "False alarms per case found",
        ],
        rows,
    )


def _replace_block(text: str, tag: str, body: str) -> str:
    return re.sub(
        rf"(<!-- {tag}:START -->\n).*?(\n<!-- {tag}:END -->)",
        lambda m: m.group(1) + body + m.group(2),
        text,
        flags=re.S,
    )


def update_readme_headline(R: dict, readme: Path) -> bool:
    """Refresh the generated blocks (HEADLINE and TABLE markers) in the README."""
    if not readme.exists():
        return False
    text = readme.read_text(encoding="utf-8")
    new = _replace_block(text, "HEADLINE", headline(R))
    new = _replace_block(new, "TABLE", readme_table(R))
    if new != text:
        readme.write_text(new, encoding="utf-8")
        return True
    return False
